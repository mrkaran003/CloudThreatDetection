# EXCEL REPORT
# =====================================================

@report.route("/report/excel")
@login_required
def generate_excel():

    workbook = Workbook()

    sheet = workbook.active

    sheet.title = "Threat Report"

    sheet.append([
        "Filename",
        "Severity",
        "Detected At"
    ])

    threats = ThreatLog.query.order_by(
        ThreatLog.detected_at.desc()
    ).all()

    for threat in threats:

        sheet.append([
            threat.filename,
            threat.severity,
            str(threat.detected_at)
        ])

    output = BytesIO()

    workbook.save(output)

    output.seek(0)

    return send_file(
        output,
        as_attachment=True,
        download_name="CloudShield_Report.xlsx",
        mimetype="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    )